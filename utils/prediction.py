"""
Prediction and Explainable AI Engine.
Handles single-patient inference, SHAP local attributions, batch CSV inference,
and local prediction history tracking.
"""

import os
import json
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional
import numpy as np
import pandas as pd
import joblib
import shap
from sklearn.pipeline import Pipeline

from utils.preprocessing import (
    FEATURE_NAMES,
    NUMERICAL_FEATURES,
    CATEGORICAL_FEATURES,
    FEATURE_METADATA,
    validate_input_data,
    validate_batch_dataframe,
)

PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODEL_PATH = PROJECT_ROOT / "model" / "heart_disease_rf_model.joblib"
HISTORY_PATH = PROJECT_ROOT / "reports" / "prediction_history.json"


class HeartDiseasePredictor:
    """
    Diagnostic inference engine providing validated predictions,
    calibrated probabilities, SHAP explainability, and history tracking.
    """

    def __init__(self, model_name: str = "Random Forest"):
        self.model_name = model_name
        self.pipeline: Pipeline = self._load_pipeline(model_name)
        self.preprocessor = self.pipeline.named_steps["preprocessor"]
        self.classifier = self.pipeline.named_steps["classifier"]
        
        # Initialize SHAP explainer for Random Forest
        self._explainer = None
        if hasattr(self.classifier, "estimators_"):
            try:
                self._explainer = shap.TreeExplainer(self.classifier)
            except Exception:
                self._explainer = None

    def _load_pipeline(self, model_name: str) -> Pipeline:
        mapping = {
            "Random Forest": PROJECT_ROOT / "model" / "heart_disease_rf_model.joblib",
            "Logistic Regression": PROJECT_ROOT / "model" / "heart_disease_logreg_model.joblib",
            "Decision Tree": PROJECT_ROOT / "model" / "heart_disease_dtree_model.joblib",
        }
        target = mapping.get(model_name, MODEL_PATH)
        if not target.exists():
            from src.model_training import train_and_evaluate_all_models
            train_and_evaluate_all_models()
        return joblib.load(target)

    def predict(self, input_dict: Dict[str, Any], save_history: bool = True) -> Dict[str, Any]:
        """
        Executes single patient prediction, calculates SHAP attributions,
        and logs to local history.
        """
        # Validate inputs & enforce exact 13 column order
        df_input = validate_input_data(input_dict)

        # Pipeline prediction
        raw_pred = int(self.pipeline.predict(df_input)[0])
        probabilities = self.pipeline.predict_proba(df_input)[0]
        prob_disease = float(probabilities[1])
        prob_healthy = float(probabilities[0])

        # Risk stratification tier
        if prob_disease < 0.35:
            risk_level = "Low Risk"
            badge_color = "#16a34a"
        elif prob_disease < 0.65:
            risk_level = "Moderate Risk"
            badge_color = "#f59e0b"
        else:
            risk_level = "High Risk"
            badge_color = "#dc2626"

        label = (
            "Heart Disease Detected"
            if raw_pred == 1
            else "No Heart Disease Detected"
        )

        # Compute SHAP local contributions if supported
        shap_analysis = self._compute_shap_explanation(df_input)

        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        result = {
            "prediction": raw_pred,
            "prediction_label": label,
            "probability_disease": prob_disease,
            "probability_no_disease": prob_healthy,
            "confidence": float(max(probabilities)),
            "risk_level": risk_level,
            "badge_color": badge_color,
            "features_used": FEATURE_NAMES,
            "input_parameters": input_dict,
            "timestamp": timestamp,
            "model_used": self.model_name,
            "shap_analysis": shap_analysis,
            "disclaimer": (
                "Educational Demonstration Only: This prediction is generated by an academic "
                "Machine Learning model (Random Forest) trained on the 1988 UCI Cleveland dataset. "
                "It is strictly for technical and educational evaluation and CANNOT replace "
                "clinical medical diagnosis, laboratory testing, or physician consultation. "
                "Feature importance reflects statistical correlation, not physiological causation."
            ),
        }

        if save_history:
            self._save_to_history(result)

        return result

    def _compute_shap_explanation(self, df_input: pd.DataFrame) -> Dict[str, Any]:
        """Calculates local feature contributions using SHAP."""
        if self._explainer is None:
            return {"available": False, "contributions": {}}

        try:
            transformed_input = self.preprocessor.transform(df_input)
            sv = self._explainer.shap_values(transformed_input)
            
            # sv shape: (1, 25, 2) or (1, 25)
            if isinstance(sv, list) and len(sv) == 2:
                disease_sv = sv[1][0]
            elif isinstance(sv, np.ndarray) and sv.ndim == 3:
                disease_sv = sv[0, :, 1]
            else:
                disease_sv = sv[0]

            feat_names_out = self.preprocessor.get_feature_names_out()

            # Aggregate back to 13 clinical features
            agg_shap: Dict[str, float] = {f: 0.0 for f in FEATURE_NAMES}
            for col_name, val in zip(feat_names_out, disease_sv):
                raw_col = col_name.split("__")[1].split("_")[0]
                agg_shap[raw_col] = agg_shap.get(raw_col, 0.0) + float(val)

            # Sort by absolute magnitude
            sorted_shap = sorted(agg_shap.items(), key=lambda x: abs(x[1]), reverse=True)

            top_risk_increasing = [
                {"feature": k, "shap_value": round(v, 4), "impact": "Pushed Risk Up"}
                for k, v in sorted_shap if v > 0
            ]
            top_risk_decreasing = [
                {"feature": k, "shap_value": round(v, 4), "impact": "Pushed Risk Down"}
                for k, v in sorted_shap if v < 0
            ]

            # Generate natural language summary
            summary_parts = []
            if top_risk_increasing:
                names = [FEATURE_METADATA.get(item["feature"], {}).get("label", item["feature"]) for item in top_risk_increasing[:3]]
                summary_parts.append(f"Elevating risk factors: {', '.join(names)}.")
            if top_risk_decreasing:
                names = [FEATURE_METADATA.get(item["feature"], {}).get("label", item["feature"]) for item in top_risk_decreasing[:2]]
                summary_parts.append(f"Protective / lower-risk indicators: {', '.join(names)}.")

            nl_explanation = " ".join(summary_parts) if summary_parts else "Balanced clinical profile with low divergence."

            return {
                "available": True,
                "contributions": dict(sorted_shap),
                "top_increasing": top_risk_increasing[:4],
                "top_decreasing": top_risk_decreasing[:4],
                "summary": nl_explanation,
                "note": "SHAP feature contributions represent model decision mechanics and do not indicate direct medical causation.",
            }
        except Exception as e:
            return {"available": False, "error": str(e), "contributions": {}}

    def predict_batch(self, df_raw: pd.DataFrame) -> Tuple[pd.DataFrame, Dict[str, Any]]:
        """
        Performs batch inference on an uploaded CSV DataFrame.
        Returns the annotated DataFrame with prediction columns and summary stats.
        """
        clean_df, warnings = validate_batch_dataframe(df_raw)

        preds = self.pipeline.predict(clean_df)
        probas = self.pipeline.predict_proba(clean_df)[:, 1]

        result_df = clean_df.copy()
        result_df["Heart_Disease_Prediction"] = [
            "Positive (Disease Detected)" if p == 1 else "Negative (No Disease)" for p in preds
        ]
        result_df["Disease_Probability_%"] = np.round(probas * 100, 2)
        result_df["Risk_Level"] = [
            "High Risk" if p >= 0.65 else ("Moderate Risk" if p >= 0.35 else "Low Risk")
            for p in probas
        ]

        summary = {
            "total_records": len(result_df),
            "positive_count": int(np.sum(preds == 1)),
            "negative_count": int(np.sum(preds == 0)),
            "high_risk_count": int(np.sum(probas >= 0.65)),
            "moderate_risk_count": int(np.sum((probas >= 0.35) & (probas < 0.65))),
            "low_risk_count": int(np.sum(probas < 0.35)),
            "warnings": warnings,
        }

        return result_df, summary

    def _save_to_history(self, record: Dict[str, Any]):
        """Persists a prediction record to reports/prediction_history.json."""
        try:
            HISTORY_PATH.parent.mkdir(parents=True, exist_ok=True)
            history = self.load_history()
            
            # Format minimal PII-free history entry
            entry = {
                "id": len(history) + 1,
                "timestamp": record["timestamp"],
                "model": record["model_used"],
                "age": record["input_parameters"].get("age"),
                "sex": "Male" if record["input_parameters"].get("sex") == 1 else "Female",
                "prediction": record["prediction_label"],
                "probability": round(record["probability_disease"] * 100, 1),
                "risk_level": record["risk_level"],
                "inputs": record["input_parameters"],
            }
            history.insert(0, entry) # newest first

            # Keep latest 100 entries
            history = history[:100]

            with open(HISTORY_PATH, "w", encoding="utf-8") as f:
                json.dump(history, f, indent=2)
        except Exception:
            pass

    @staticmethod
    def load_history() -> List[Dict[str, Any]]:
        """Loads historical predictions from disk."""
        if not HISTORY_PATH.exists():
            return []
        try:
            with open(HISTORY_PATH, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return []

    @staticmethod
    def clear_history():
        """Clears stored prediction history."""
        if HISTORY_PATH.exists():
            with open(HISTORY_PATH, "w", encoding="utf-8") as f:
                json.dump([], f)
